"""Measure the real bounds of every building-kit mesh the generator can place.

Needs a running UE5 game with the plugin (``GetStaticMeshBounds``). Every distinct
facade piece asset used by 40 generated scenarios and by synthetic buildings of every
style is measured; the result is printed as the module source for
``src/procedural/facade_piece_bounds.py``:

    PYTHONPATH=. python bin/measure_facade_piece_bounds.py > src/procedural/facade_piece_bounds.py

Bounds are (x_min, y_min, z_min, x_max, y_max, z_max) in metres in the mesh's own
frame with y mirrored to the generator's convention.
"""

import asyncio
from pathlib import Path
from typing import Dict, Set, Tuple

import numpy as np

from src.orchestration.dataset_generator import generate_scenario
from src.procedural.building_facade import generate_building_facade_pieces
from src.procedural.building_placement import Building
from src.procedural.city_sample_assets import BUILDING_STYLES
from src.ue5.backend import UE5Backend
from src.utils.config_loader import load_scenario_config

CM = 100.0
SCENARIOS = 40
BOUNDS = (-150.0, -150.0, 150.0, 150.0)
SYNTHETIC_SIZES = ((18.0, 14.0, 12.0), (30.0, 22.0, 45.0), (24.0, 24.0, 90.0))


def _asset_paths() -> Set[str]:
    """Every facade piece asset used by generated scenarios and by every style."""
    config = load_scenario_config(Path("configs/scenario_templates/urban_dense.yaml"))
    paths: Set[str] = set()
    for seed in range(SCENARIOS):
        scenario = generate_scenario(seed, config, BOUNDS, f"paths_{seed}")
        paths |= {piece.asset_path for piece in scenario.building_facade_pieces}
    for name, style in BUILDING_STYLES.items():
        for index, (width, depth, height) in enumerate(SYNTHETIC_SIZES):
            building = Building(index, np.zeros(2), width, depth, height, style_name=name)
            paths |= {p.asset_path for p in generate_building_facade_pieces(building, style)}
    return paths


async def _measure(paths: Set[str]) -> Dict[str, Tuple[float, ...]]:
    """Bounds per asset path."""
    table: Dict[str, Tuple[float, ...]] = {}
    async with UE5Backend("ws://localhost:8765", timeout_seconds=120.0) as backend:
        for path in sorted(paths):
            reply = await backend.call("GetStaticMeshBounds", {"asset_path": path})
            table[path] = (
                round((reply["origin_x"] - reply["extent_x"]) / CM, 3),
                round(-(reply["origin_y"] + reply["extent_y"]) / CM, 3),
                round((reply["origin_z"] - reply["extent_z"]) / CM, 3),
                round((reply["origin_x"] + reply["extent_x"]) / CM, 3),
                round(-(reply["origin_y"] - reply["extent_y"]) / CM, 3),
                round((reply["origin_z"] + reply["extent_z"]) / CM, 3),
            )
    return table


def main() -> None:
    """Print the generated module."""
    table = asyncio.run(_measure(_asset_paths()))
    print('"""Real bounds of every building-kit mesh, measured live.')
    print()
    print("GENERATED by ``bin/measure_facade_piece_bounds.py`` -- do not edit by hand. Each entry")
    print("is (x_min, y_min, z_min, x_max, y_max, z_max) in metres in the mesh's own frame, with")
    print('y mirrored to the generator\'s convention."""')
    print()
    print("from typing import Dict, Tuple")
    print()
    print("FACADE_PIECE_BOUNDS: Dict[str, Tuple[float, float, float, float, float, float]] = {")
    for path, bounds in table.items():
        print(f'    "{path}": {bounds},')
    print("}")


if __name__ == "__main__":
    main()

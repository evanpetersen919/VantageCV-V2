"""Measure every City Sample vehicle model's real ground-truth box and print
the module source for ``src/procedural/vehicle_bounds.py``.

Needs a running UE5 game with the plugin (the bounds come from its
``GetStaticMeshBounds`` RPC):

    PYTHONPATH=. python bin/measure_vehicle_bounds.py > src/procedural/vehicle_bounds.py

A vehicle's box is the union of the extents of its body shell, wheels and glass
meshes. Doors are left out because each door mesh includes the side mirror (a
sedan door reaches 105 cm from the centreline against a body of 94 cm). The
interior-frame mesh is left out because it is wider than the visible vehicle on
the bus, box truck and van (313 cm against 280 cm on the bus, confirmed by
rendering them from above), and lamps and the steering wheel lie inside the
body's extent. All meshes
share one origin (parts spawn at zero relative offset), so extents combine
directly.
"""

import asyncio
from typing import Dict, List, Tuple

from src.procedural.city_sample_assets import VEHICLE_ASSET_PATHS, VEHICLE_PART_PATHS
from src.ue5.backend import UE5Backend

BOX_PART_PREFIXES = ("SM_Wheel_",)
GLASS_MARKER = "Trans"


def _in_box(part_name: str) -> bool:
    """Whether a part mesh contributes to the vehicle's box."""
    return part_name.startswith(BOX_PART_PREFIXES) or GLASS_MARKER in part_name


CM = 100.0


async def _extents(backend: UE5Backend, path: str) -> Tuple[float, ...]:
    reply = await backend.call("GetStaticMeshBounds", {"asset_path": path})
    return (
        reply["origin_x"] - reply["extent_x"],
        reply["origin_y"] - reply["extent_y"],
        reply["origin_z"] - reply["extent_z"],
        reply["origin_x"] + reply["extent_x"],
        reply["origin_y"] + reply["extent_y"],
        reply["origin_z"] + reply["extent_z"],
    )


async def measure() -> Dict[str, Tuple[float, ...]]:
    """Per model folder: (length, width, height, center_x, center_y, z_min) in metres."""
    backend = UE5Backend("ws://localhost:8765", timeout_seconds=120.0)
    table: Dict[str, Tuple[float, ...]] = {}
    for paths in VEHICLE_ASSET_PATHS.values():
        for body in paths:
            folder = body.split("/")[3]
            boxes: List[Tuple[float, ...]] = [await _extents(backend, body)]
            for part in VEHICLE_PART_PATHS.get(folder, []):
                if _in_box(part.split("/")[-1]):
                    boxes.append(await _extents(backend, part))
            low = [min(box[axis] for box in boxes) for axis in range(3)]
            high = [max(box[axis + 3] for box in boxes) for axis in range(3)]
            table[folder] = (
                round((high[0] - low[0]) / CM, 3),
                round((high[1] - low[1]) / CM, 3),
                round((high[2] - low[2]) / CM, 3),
                round((high[0] + low[0]) / 2.0 / CM, 3),
                round((high[1] + low[1]) / 2.0 / CM, 3),
                round(low[2] / CM, 3),
            )
    return table


def main() -> None:
    """Print the generated module."""
    table = asyncio.run(measure())
    print('"""Real ground-truth box of every City Sample vehicle model, measured live.')
    print()
    print("GENERATED by ``bin/measure_vehicle_bounds.py`` -- do not edit by hand. Each")
    print("entry is (length, width, height, center_x, center_y, z_min) in metres in the")
    print("mesh's own frame (+X forward, origin at the mesh origin): the union of the")
    print("body, wheel and glass meshes (doors are excluded, they carry the mirrors,")
    print("and so is the interior frame, which overstates the big vehicles). The center")
    print('offset is where the box\'s center sits relative to the placement point."""')
    print()
    print("from typing import Dict, Tuple")
    print()
    print("VEHICLE_MODEL_BOUNDS: Dict[str, Tuple[float, float, float, float, float, float]] = {")
    for folder, row in table.items():
        print(f'    "{folder}": {row},')
    print("}")


if __name__ == "__main__":
    main()
